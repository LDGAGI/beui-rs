//! Derived files must not drift from their source.
//!
//! Four files are generated rather than written by hand:
//!
//! - `assets/globals.css` — verbatim (`globals_verbatim.rs`)
//! - `assets/globals.tailwind.css` — verbatim minus the `@import "tailwindcss";`
//!   line, because `gallery/tailwind.css` imports the framework itself
//! - `gallery/public/assets/fonts/*.woff2` — byte-identical to `assets/fonts/*`
//! - `assets/beui.css` — the prebuilt component utilities, compiled by
//!   `scripts/build-beui-css.sh` so consumers need no Tailwind build
//!
//! `scripts/sync-tailwind-input.sh` regenerates the first three;
//! `scripts/build-beui-css.sh` regenerates the last.

use std::path::{Path, PathBuf};

const TAILWIND_COPY: &str = "assets/globals.tailwind.css";
const FONT_DIR: &str = "assets/fonts";
const PUBLIC_FONT_DIR: &str = "../../gallery/public/assets/fonts";

fn read(path: impl AsRef<Path>) -> String {
    std::fs::read_to_string(path.as_ref())
        .unwrap_or_else(|error| panic!("reading {}: {error}", path.as_ref().display()))
}

#[test]
fn tailwind_copy_is_globals_css_minus_the_framework_import() {
    let verbatim = beui_theme::globals_css();
    let prefix = "@import \"tailwindcss\";\n";
    assert!(verbatim.starts_with(prefix), "globals.css head changed");

    assert_eq!(
        read(TAILWIND_COPY),
        &verbatim[prefix.len()..],
        "{TAILWIND_COPY} is stale — run scripts/sync-tailwind-input.sh"
    );
}

#[test]
fn public_fonts_match_the_theme_crate() {
    let mut expected: Vec<String> = std::fs::read_dir(FONT_DIR)
        .expect("assets/fonts")
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.file_name().to_string_lossy().into_owned())
        .filter(|name| name.ends_with(".woff2"))
        .collect();
    expected.sort();
    let mut listed = beui_theme::FONT_FILES.to_vec();
    listed.sort();
    assert_eq!(
        expected, listed,
        "FONT_FILES no longer lists exactly the files in {FONT_DIR}"
    );

    let public = PathBuf::from(PUBLIC_FONT_DIR);
    if !public.exists() {
        eprintln!("skipping: {PUBLIC_FONT_DIR} is not present");
        return;
    }
    for name in &expected {
        let from = std::fs::read(Path::new(FONT_DIR).join(name)).expect("read source font");
        let to = std::fs::read(public.join(name))
            .unwrap_or_else(|error| panic!("reading {}: {error}", public.join(name).display()));
        assert_eq!(
            from, to,
            "{PUBLIC_FONT_DIR}/{name} differs — run scripts/sync-tailwind-input.sh"
        );
    }
}

#[test]
fn font_css_covers_every_file() {
    let css = beui_theme::fonts_css();
    for name in beui_theme::FONT_FILES {
        assert!(
            css.contains(&format!("{}/{name}'", beui_theme::FONT_BASE_PATH)),
            "fonts_css() is missing {name}"
        );
        assert!(
            css.contains("font-weight: 100 900;"),
            "fonts_css() must declare the variable range"
        );
    }
    assert_eq!(
        css.matches("@font-face").count(),
        beui_theme::FONT_FILES.len()
    );
    // Both family names `globals.css` points at.
    assert!(css.contains("font-family: 'Geist';"));
    assert!(css.contains("font-family: 'Geist Mono';"));
}

/// `assets/beui.css` is generated by `scripts/build-beui-css.sh`. The file is
/// always shipped (the `prebuilt-css` feature only decides whether it is
/// compiled into the binary), so a truncated or preflight-carrying
/// regeneration fails here rather than in a consumer's page.
#[test]
fn prebuilt_stylesheet_is_present_and_complete() {
    let css = read("assets/beui.css");
    assert!(
        !css.contains("webkit-text-size-adjust"),
        "assets/beui.css must not carry Tailwind's preflight — it is injected \
         into an existing page. Run scripts/build-beui-css.sh after editing the \
         generator."
    );
    for needle in [
        ".bg-primary",
        ".rounded-xl",
        ".animate-marquee",
        "box-sizing:border-box",
    ] {
        assert!(
            css.contains(needle),
            "assets/beui.css is missing {needle} — run scripts/build-beui-css.sh"
        );
    }
}
