#!/usr/bin/env node
/**
 * Generate `crates/beui/src/icons.rs` from the Lucide icon sources.
 *
 * beUI renders every glyph with `lucide-react`, and the port keeps the same
 * path data. Rather than
 * transcribing the geometry by hand, this reads the icon nodes straight out of
 * the installed `lucide-react` package and emits one Dioxus component per
 * glyph, with Lucide's own default SVG attributes.
 *
 * Usage: node scripts/gen-icons.mjs [path-to-lucide-react]
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const candidates = [
  process.argv[2] ?? process.env.LUCIDE_REACT_DIR,
  join(root, "node_modules/lucide-react"),
].filter(Boolean);

const pkg = candidates.find((p) => existsSync(join(p, "dist/esm/icons")));
if (!pkg) {
  console.error("could not find lucide-react; pass its path as the first argument");
  process.exit(1);
}
const iconsDir = join(pkg, "dist/esm/icons");

/** PascalCase component name -> kebab-case lucide file. */
const ICONS = {
  AlertCircle: "alert-circle",
  AlertTriangle: "alert-triangle",
  ArrowLeft: "arrow-left",
  ArrowRight: "arrow-right",
  ArrowUpRight: "arrow-up-right",
  Calendar: "calendar",
  CalendarDays: "calendar-days",
  Check: "check",
  CheckCircle2: "check-circle-2",
  ChevronDown: "chevron-down",
  ChevronLeft: "chevron-left",
  ChevronRight: "chevron-right",
  ChevronUp: "chevron-up",
  Circle: "circle",
  Clock: "clock",
  Download: "download",
  Eye: "eye",
  EyeOff: "eye-off",
  Info: "info",
  Loader: "loader",
  Loader2: "loader-2",
  LoaderCircle: "loader-circle",
  Mail: "mail",
  Minus: "minus",
  Moon: "moon",
  Pipette: "pipette",
  Plus: "plus",
  Search: "search",
  Sparkles: "sparkles",
  Sun: "sun",
  Trash2: "trash-2",
  X: "x",
};

/** Attribute names Lucide writes; the rest are rejected so a typo is loud. */
const ATTRS = {
  d: "d",
  cx: "cx",
  cy: "cy",
  r: "r",
  x: "x",
  y: "y",
  width: "width",
  height: "height",
  rx: "rx",
  ry: "ry",
  x1: "x1",
  y1: "y1",
  x2: "x2",
  y2: "y2",
  points: "points",
};

function readNode(file) {
  const source = readFileSync(file, "utf8");
  // Several names are thin aliases (`alert-circle` -> `circle-alert`).
  const alias = source.match(/export \{ default \} from '\.\/([^']+)\.js'/);
  if (alias) return readNode(join(iconsDir, `${alias[1]}.js`));
  const match = source.match(/const __iconNode = (\[[\s\S]*?\]);\nconst/);
  if (!match) throw new Error(`no __iconNode in ${file}`);
  // Data-only literal: arrays, objects, strings.
  return eval(match[1]);
}

function attrLine(tag, key, value) {
  if (!(key in ATTRS)) throw new Error(`${tag}: unsupported attribute ${key}`);
  return `${key}: ${JSON.stringify(String(value))}`;
}

function element(tag, attrs) {
  const fields = Object.entries(attrs)
    .filter(([key]) => key !== "key")
    .map(([key, value]) => attrLine(tag, key, value));
  return `            ${tag} { ${fields.join(", ")} }`;
}

function component(name, kebab) {
  const node = readNode(join(iconsDir, `${kebab}.js`));
  const children = node.map(([tag, attrs]) => element(tag, attrs)).join("\n");
  return `/// Lucide \`${kebab}\` — path data copied from \`lucide-react\`.
#[component]
pub fn Icon${name}(
    #[props(default)] class: Option<String>,
    #[props(default)] stroke_width: Option<String>,
) -> Element {
    rsx! {
        svg {
            class: class,
            xmlns: "http://www.w3.org/2000/svg",
            width: "24",
            height: "24",
            view_box: "0 0 24 24",
            fill: "none",
            stroke: "currentColor",
            stroke_width: stroke_width.unwrap_or_else(|| "2".to_string()),
            stroke_linecap: "round",
            stroke_linejoin: "round",
${children}
        }
    }
}`;
}

const header = `//! Lucide glyphs, generated by \`scripts/gen-icons.mjs\`.
//!
//! beUI draws every icon with \`lucide-react\`; the port keeps Lucide's exact
//! path data and its default SVG attributes — \`24\` box,
//! \`fill="none"\`, \`stroke="currentColor"\`, \`stroke-width={2}\`, round caps
//! and joins. Sizing comes from the caller's \`class\`, exactly as the source's
//! \`className\` does (\`[&_svg]:h-4\` and friends).
//!
//! Regenerate with \`node scripts/gen-icons.mjs\`.

#![allow(non_snake_case)]

use dioxus::prelude::*;

`;

const body = Object.entries(ICONS)
  .map(([name, kebab]) => component(name, kebab))
  .join("\n\n");

const out = join(root, "crates/beui/src/icons.rs");
writeFileSync(out, `${header}${body}\n`);
console.log(`wrote ${out} (${Object.keys(ICONS).length} icons)`);
